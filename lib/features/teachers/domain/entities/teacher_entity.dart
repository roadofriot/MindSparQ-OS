class TeacherEntity {
  final String id;
  final String fullName;
  final String employeeCode;
  final String subject;
  final String schoolId;
  final String phone;
  final String status;

  const TeacherEntity({
    required this.id,
    required this.fullName,
    required this.employeeCode,
    required this.subject,
    required this.schoolId,
    required this.phone,
    required this.status,
  });
}
